    fun findPresetForQuery(query: String): Anatomy3DModel? {
        val q = query.lowercase().trim()
        return when {
            q.contains("brain") || q.contains("मस्तिष्क") || q.contains("दिमाग") || q.contains("cerebr") || q.contains("hippocampus") -> allModels[0]
            q.contains("cell") || q.contains("कोशिका") || q.contains("nucleus") || q.contains("केंद्रक") || q.contains("cytoplasm") -> allModels[1]
            q.contains("heart") || q.contains("हृदय") || q.contains("दिल") || q.contains("ventricle") || q.contains("aorta") -> allModels[2]
            q.contains("bone") || q.contains("हड्डी") || q.contains("femur") || q.contains("marrow") || q.contains("अस्थि") || q.contains("skeleton") -> allModels[3]
            q.contains("neuron") || q.contains("न्यूरॉन") || q.contains("nerve") || q.contains("तंत्रिका") || q.contains("axon") -> allModels[4]
            q.contains("lung") || q.contains("फेफड़") || q.contains("alveoli") || q.contains("trachea") || q.contains("श्वसन") -> allModels[5]
            q.contains("kidney") || q.contains("किडनी") || q.contains("वृक्क") || q.contains("nephron") -> allModels[6]
            q.contains("eye") || q.contains("आंख") || q.contains("नेत्र") || q.contains("retina") || q.contains("cornea") -> allModels[7]
            q.contains("dna") || q.contains("डीएनए") || q.contains("gene") || q.contains("जीन") || q.contains("chromosome") -> allModels[8]
            q.contains("mitochondri") || q.contains("माइटोकॉन्ड्रिया") || q.contains("atp") -> allModels[9]
            else -> null
        }
    }

